/// `patchcli prepare --verify`: diagnostic parsing, error → prepared-view attribution, the
/// demote-and-retry loop (incl. the pre-existing-error re-promotion and the bounded stops), the
/// `native_views:` config round-trip, and the prepare/fingerprint consistency of a kept-native view.
final class PrepareVerifierTests: XCTestCase {

    typealias D = PrepareVerifier.Diagnostic

    // MARK: - Diagnostics

    func testParseDiagnosticsExtractsErrorsOnlyAndDedupes() {
        let log = """
        Compiling VerifyApp ProfileCard.swift
        /tmp/p/App/Patch/Generated/PatchThunks.generated.swift:79:86: error: cannot find 'AvatarBadge' in scope
        /tmp/p/App/Patch/Generated/PatchThunks.generated.swift:79:86: error: cannot find 'AvatarBadge' in scope
        /tmp/p/App/Speed.swift:318:33: error: the compiler is unable to type-check this expression in reasonable time; try breaking up the expression into distinct sub-expressions
        /tmp/p/App/Speed.swift:12:5: warning: variable 'x' was never used
        ld: error: something not swift
        """
        let ds = PrepareVerifier.parseDiagnostics(log)
        XCTAssertEqual(ds.count, 2)
        XCTAssertEqual(ds[0], D(file: "/tmp/p/App/Patch/Generated/PatchThunks.generated.swift", line: 79, column: 86,
                                message: "cannot find 'AvatarBadge' in scope"))
        XCTAssertEqual(ds[1].line, 318)
        XCTAssertEqual(ds[1].column, 33)
        XCTAssertTrue(ds[1].message.hasPrefix("the compiler is unable to type-check"))
    }

    // MARK: - Attribution

    static let appFile = """
    import SwiftUI

    struct Helper { let x = 1 }

    struct SpeedToolPanel: View {
        let speed: Double
        dynamic var body: some View {
            VStack {
                Text("\\(speed)")
            }
