    #endif
    // PATCH-THUNKS-END
    """

    static let generatedFile = """
    // PatchThunks.generated.swift — GENERATED BY `patchcli prepare`. DO NOT EDIT.
    #if canImport(SwiftUI)
    import SwiftUI
    extension ProfileCard {
        @_dynamicReplacement(for: body)
        var __patchedBody: some View { body }
    }

    extension ProfileCard {
        @MainActor func __patchSlots() -> [String: ([String]) -> AnyView] {
            var __s: [String: ([String]) -> AnyView] = [:]
            __s["op_2"] = { (_: [String]) -> AnyView in AnyView(AvatarBadge(initials: initials)) }
            return __s
        }
    }
